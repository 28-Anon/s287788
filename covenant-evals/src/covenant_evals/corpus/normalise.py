"""Turning filing HTML into stable plain text.

Everything downstream depends on one property: **the same input must always produce
byte-identical output.** Your labels store character offsets into this text. If the
normaliser changes, every offset shifts and every label silently starts pointing at the
wrong words — with no error, no test failure, and no way to notice except by reading them.

So: NORMALISER_VERSION is recorded in the manifest alongside every hash. If you change the
rules below, bump it. Any agreement whose stored version does not match the current one is
reported as stale by `corpus status`, and items labelled against it must be re-checked.

The rules are deliberately few. Every transformation is a chance to make the text differ
from what a human sees in the original filing, and citations have to match.
"""

from __future__ import annotations

import hashlib
import re
from html.parser import HTMLParser

#: Bump this whenever the rules below change. Week 3 will bump it when section
#: segmentation lands.
NORMALISER_VERSION = 1

#: Tags whose content is markup machinery, never prose.
_DROP_CONTENT = frozenset({"script", "style", "head", "title"})

#: Tags that end a line of text. Filing HTML is mostly <p>, <div> and tables.
_BLOCK = frozenset(
    {
        "p",
        "div",
        "br",
        "tr",
        "li",
        "table",
        "thead",
        "tbody",
        "h1",
        "h2",
        "h3",
        "h4",
        "h5",
        "h6",
        "section",
        "article",
        "hr",
    }
)


class _TextExtractor(HTMLParser):
    """Pulls prose out of filing HTML.

    Uses the standard library parser rather than regular expressions because filing HTML
    is generated by a hundred different vendors' tooling and is frequently malformed in
    ways a regex handles silently and wrongly.
    """

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self._suppress_depth = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag in _DROP_CONTENT:
            self._suppress_depth += 1
        elif tag in _BLOCK:
            self.parts.append("\n")
        elif tag == "td":
            self.parts.append(" ")

    def handle_endtag(self, tag: str) -> None:
        if tag in _DROP_CONTENT:
            self._suppress_depth = max(0, self._suppress_depth - 1)
        elif tag in _BLOCK:
            self.parts.append("\n")

    def handle_data(self, data: str) -> None:
        if self._suppress_depth == 0:
            self.parts.append(data)


def normalise_html(html: str) -> str:
    """HTML in, stable plain text out.

    The complete list of transformations, in order. Nothing else happens to the text:

    1. Drop the contents of script, style, head and title
    2. Block-level tags become newlines (one at each end, so adjacent blocks are
       separated by a blank line); table cells become spaces
    3. HTML entities are decoded (``&amp;`` becomes ``&``)
    4. Non-breaking spaces and other Unicode spaces become ordinary spaces
    5. Windows and old-Mac line endings become ``\\n``
    6. Runs of spaces and tabs collapse to one space
    7. Leading and trailing whitespace is stripped from each line
    8. Three or more blank lines collapse to one blank line
    9. Leading and trailing whitespace on the whole document is stripped, and a single
       trailing newline is added

    Note what is *not* done: quotes are not straightened, dashes are not normalised, case
    is untouched. Those would make the text easier to process and harder to cite, and
    citation is the point of this project.
    """
    extractor = _TextExtractor()
    extractor.feed(html)
    extractor.close()
    text = "".join(extractor.parts)

    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # Explicit escapes, not the literal characters: invisible whitespace in source
    # code is exactly the kind of thing that breaks silently on a copy-paste.
    text = re.sub(r"[\u00a0\u1680\u2000-\u200a\u202f\u205f\u3000]", " ", text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n[ \t]+", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip() + "\n"


def sha256_text(text: str) -> str:
    """Hash of the normalised text. This is what an item's `doc_sha256` pins."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_bytes(raw: bytes) -> str:
    """Hash of the file exactly as EDGAR served it, before any processing."""
    return hashlib.sha256(raw).hexdigest()
