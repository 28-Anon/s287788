"""Tests for HTML normalisation.

The property under test throughout is **stability**: the same input must always produce
identical output, because character offsets in every label point into this text.
"""

from covenant_evals.corpus.normalise import (
    NORMALISER_VERSION,
    normalise_html,
    sha256_bytes,
    sha256_text,
)


def test_tags_are_stripped_and_entities_decoded():
    assert normalise_html("<p>Consolidated EBITDA &amp; Leverage</p>").strip() == (
        "Consolidated EBITDA & Leverage"
    )


def test_script_and_style_contents_are_dropped():
    html = "<style>p{color:red}</style><script>var x=1;</script><p>Section 7.02</p>"
    assert normalise_html(html).strip() == "Section 7.02"


def test_block_tags_are_separated_by_a_blank_line():
    # Both the opening and closing tag emit a newline, so adjacent blocks end up with one
    # blank line between them. That is deliberate: the .txt file is read by a human
    # writing labels, and paragraph breaks make it navigable.
    text = normalise_html("<div>7.01 Indebtedness</div><div>7.02 Liens</div>")
    assert "7.01 Indebtedness\n\n7.02 Liens" in text


def test_non_breaking_spaces_become_ordinary_spaces():
    text = normalise_html("<p>not&nbsp;to&nbsp;exceed</p>")
    assert "not to exceed" in text
    assert " " not in text


def test_runs_of_whitespace_collapse():
    assert "greater of $35,000,000" in normalise_html("<p>greater   of \t $35,000,000</p>")


def test_blank_lines_collapse_to_at_most_one():
    text = normalise_html("<p>a</p><br/><br/><br/><br/><p>b</p>")
    assert "\n\n\n" not in text


def test_output_always_ends_with_exactly_one_newline():
    for html in ["<p>a</p>", "<p>a</p>\n\n\n", "   <p>a</p>   "]:
        text = normalise_html(html)
        assert text.endswith("\n")
        assert not text.endswith("\n\n")


def test_quotes_and_dashes_are_left_alone():
    # Deliberate: citations must match the document as filed. Straightening quotes would
    # make the text tidier and the citations wrong.
    text = normalise_html("<p>the “Borrower” — as defined</p>")
    assert "“Borrower”" in text
    assert "—" in text


def test_normalisation_is_deterministic():
    html = "<div><p>Section 7.02(b)</p><table><tr><td>a</td><td>b</td></tr></table></div>"
    assert normalise_html(html) == normalise_html(html)
    assert sha256_text(normalise_html(html)) == sha256_text(normalise_html(html))


def test_malformed_html_does_not_raise():
    # Filing HTML is generated by dozens of vendors' tooling and is routinely broken.
    for broken in ["<p>unclosed", "<div><p>crossed</div></p>", "<<>>", "a < b and c > d"]:
        assert isinstance(normalise_html(broken), str)


def test_hashes_are_stable_and_distinct():
    assert sha256_text("abc") == sha256_text("abc")
    assert sha256_text("abc") != sha256_text("abd")
    assert len(sha256_bytes(b"abc")) == 64


def test_normaliser_version_is_recorded():
    # If this fails you changed the normaliser. Bump NORMALISER_VERSION, then check every
    # already-labelled item: their character offsets have moved.
    assert NORMALISER_VERSION == 1
